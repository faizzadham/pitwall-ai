"""
Generative AI Race Strategist & Tactical Debrief Engine.
Integrates with Google Gemini API (or intelligent domain heuristics when offline/no API key)
to act as the team's Chief Race Engineer and Pit-Wall Tactician.
"""
import os
import pandas as pd

def get_gemini_client():
    api_key = os.environ.get("GEMINI_API_KEY", "")
    if not api_key:
        return None
    try:
        from google import genai
        return genai.Client(api_key=api_key)
    except Exception:
        return None

def generate_ai_strategy_brief(circuit_name: str, circuit_info: dict, predictions_df: pd.DataFrame, is_wet: bool = False, session_type: str = "Race (Grand Prix)") -> str:
    top5 = predictions_df.head(5).copy()
    p1 = top5.iloc[0]
    p2 = top5.iloc[1]
    p3 = top5.iloc[2]

    client = get_gemini_client()
    if client:
        try:
            summary = top5.to_string(index=False)
            prompt = f"""
            You are the Chief Race Strategist for an elite Formula 1 pit wall.
            Analyze the following Machine Learning prediction output for the upcoming {session_type} at {circuit_name}:

            Circuit Info:
            - Type: {circuit_info.get('type')}
            - Downforce Index: {circuit_info.get('downforce_index')}
            - Tire Degradation: {circuit_info.get('tire_degradation')}
            - Safety Car Probability: {circuit_info.get('safety_car_prob')}
            - Weather: {'Wet / Rain' if is_wet else 'Dry'}
            - Session: {session_type}

            Predicted Standings:
            {summary}

            Generate a sharp, professional 3-section Race Engineer Briefing tailored to {session_type}:
            1. **Session Outlook & Key Contenders:** Pace battle for P1 ({p1['driver']}) vs P2 ({p2['driver']}).
            2. **Tactical & Technical Setup:** Tire preparation, engine modes, aerodynamic balance, and stint management.
            3. **Key Threats & Operational Watchpoints:** Tactical pivots, track evolution, and risk mitigation.
            Keep formatting crisp with bullet points and authentic motorsport terminology.
            """
            response = client.models.generate_content(
                model="gemini-2.5-flash",
                contents=prompt
            )
            if response and response.text:
                return response.text
        except Exception:
            pass

    # Heuristic fallback based on session type
    if "Qualifying" in session_type:
        brief = f"""
### 🎙️ Pit-Wall Qualifying Strategy Debrief: {circuit_name}
*Generated by PitWall AI Intelligence Engine*

#### 1. ⏱️ Pole Position Outlook & Flying Lap Trim
- **Projected Pole Winner:** **{p1['driver']} ({p1['team']})** with high single-lap qualifying efficiency.
- **Delta Margin:** Estimated gap to P2 ({p2['driver']}) is under **0.150s**, meaning Turn 1 braking and final corner traction will decide pole.
- **Track Evolution:** Expect track grip to ramp up by **0.4s to 0.6s** between Q1 and Q3 as Pirelli rubber is laid down. Target late out-lap release in Q3.

#### 2. 🛞 Tire Preparation & Out-Lap Protocol
- **Compound:** C-Spec Soft Compound (Red Wall).
- **Surface Warming:** Requires aggressive brake duct heating and weave procedure through Sector 2 to achieve optimal **105°C** front bulk tire temperature before the final hairpin.
- **ERS Deployment:** Deploy full ERS Mode 8 (Hot Lap) on exit of final corner; maintain DRS open on main straights.

#### 3. ⚠️ Session Risks & Elimination Margins
- **Traffic Watch:** High congestion expected in the final sector before beginning flying runs. Engineer to ensure a minimum **4.0s clean air gap** ahead.
- **Cutoff Margins:** Q1 and Q2 elimination deltas projected at less than 0.250s across the midfield.
"""
        return brief

    elif "Sprint" in session_type:
        brief = f"""
### 🎙️ Pit-Wall Sprint Race Tactical Briefing: {circuit_name}
*Generated by PitWall AI Intelligence Engine*

#### 1. ⚡ Sprint Dynamics & 100km Flat-Out Pace
- **Projected Sprint Victor:** **{p1['driver']} ({p1['team']})** holding front position into Turn 1.
- **Championship Points Stakes:** FIA points awarded to top 8 finishers (P1: 8 pts down to P8: 1 pt). P3 ({p3['driver']}) must protect track position against aggressive midfield overtakes.
- **Pit Stop Protocol:** Sprint regulations feature **no mandatory pit stop**. Race will be run flag-to-flag on a single tire set.

#### 2. 🛞 Tire Thermal Degradation & Management
- **Compound Choice:** Medium Compound (Yellow) recommended for stability, or Soft (Red) for an aggressive opening 5 laps.
- **Thermal Limiting Corner:** High lateral loads at {circuit_name} will punish front-left tire shoulder if following within dirty air dirty wash (< 1.2s).
- **DRS Train Risk:** Driver must stay within 1.0s of leader to maintain DRS tow defense against trailing cars.

#### 3. ⚠️ Risk Assessment vs Grand Prix Preservation
- **Car Preservation:** Zero points scored for severe collision damage; balance aggressive overtaking with keeping the chassis intact for the main Grand Prix race tomorrow.
"""
        return brief

    elif "Practice" in session_type or "FP" in session_type:
        brief = f"""
### 🎙️ Pit-Wall Free Practice Program: {circuit_name} ({session_type})
*Generated by PitWall AI Intelligence Engine*

#### 1. 🔧 Session Run-Plan & Test Matrix
- **Benchmark Leader:** **{p1['driver']} ({p1['team']})** setting initial pace in low-fuel trim.
- **Run Plan Part A (0-25 min):** Baseline aerodynamic correlation, ride-height check, rake angle validation, and flow-vis rake evaluation.
- **Run Plan Part B (25-60 min):** High-fuel race stint simulation (110 kg fuel load) assessing tire degradation on Medium and Hard compounds.

#### 2. 📊 Aerodynamic Downforce & Mechanical Balance
- **Circuit Characteristics:** {circuit_info.get('type')} with downforce index of **{circuit_info.get('downforce_index')*100:.0f}%**.
- **Ride Setup:** High-speed curb compliance required; adjust front heave damper and rear anti-roll bar stiffness.
- **Telemetry Check:** Monitor speed trap telemetry in Sector 1 and minimum apex speeds through mid-gear corners.

#### 3. 🌡️ Tire Temperature & Track Evolution
- **Track Temperature:** Monitor asphalt temperature delta; cooler conditions will induce front graining.
- **Driver Feedback Target:** Verify turn-in stability and throttle pickup without excessive rear wheelspin on corner exit.
"""
        return brief

    # Default: Grand Prix Race
    overcut_vs_undercut = "undercut is extremely potent (gaining ~1.4s per lap on fresh rubber)" if circuit_info.get("tire_degradation") == "High" else "track position is king, favoring an extended overcut or 1-stop endurance"
    tire_plan = "Medium (Yellow) -> Hard (White) with pit window between Lap 18-24" if not is_wet else "Intermediate (Green) start with telemetry monitoring for crossover to Slicks around Lap 26"
    if circuit_info.get("tire_degradation") == "Very High":
        tire_plan = "Aggressive 2-Stop Strategy: Soft (L1-14) -> Medium (L15-36) -> Hard (L37-End)"

    brief = f"""
### 🎙️ Pit-Wall Tactical Debrief: {circuit_name} ({session_type})
*Generated by PitWall AI Intelligence Engine*

#### 1. 🏎️ First Stint Dynamics & Win Outlook
- **Projected Race Winner:** **{p1['driver']} ({p1['team']})** with a **{p1['win_prob']*100:.1f}% Win Probability** and **{p1['podium_prob']*100:.1f}% Podium Probability**.
- **Launch Phase (Turn 1):** Starting from Grid P{p1['grid_position']}, {p1['driver']} holds clean-side advantage over {p2['driver']} (P{p2['grid_position']}). Run down to Turn 1 requires aggressive battery deployment (KERS/ERS Mode 8) to break DRS tow within the initial 3 laps.
- **Pace Differential:** Our predictive models project {p1['driver']} holding a **0.18s/lap** median race pace advantage over {p2['driver']} on fuel-corrected stint simulations.

#### 2. 🛞 Pit Stop & Tire Degradation Roadmap
- **Circuit Degradation:** Rated as **{circuit_info.get('tire_degradation')}**.
- **Recommended Strategy:** **{tire_plan}**.
- **Tactical Window:** At this track, the {overcut_vs_undercut}.
- **Target In-Lap:** Prepare pit crew for defensive box if the gap back to P3 ({p3['driver']}) drops beneath **21.5 seconds** (full pit-loss delta under green flag conditions).

#### 3. ⚠️ Safety Car & Operational Contingency
- **Safety Car Risk:** Evaluated at **{circuit_info.get('safety_car_prob')*100:.0f}%** for {circuit_name}.
- **Virtual Safety Car (VSC) Protocol:** If a Neutralization occurs between Laps 14–32, execute a "Cheap Pit Stop" saving ~9.5 seconds over standard racing conditions.
- **Watchpoint:** Keep close telemetry monitoring on front-left surface tire graining for {p2['driver']} and {p3['driver']} entering the final sector.
"""
    return brief

def answer_strategist_query(user_question: str, circuit_name: str, pred_df: pd.DataFrame) -> str:
    client = get_gemini_client()
    if client:
        try:
            top_info = pred_df.head(5)[["driver", "team", "grid_position", "podium_prob"]].to_string()
            prompt = f"""
            You are the F1 Head of Strategy responding to a driver or team principal over the team radio.
            Context: {circuit_name} Grand Prix.
            Top predicted grid: {top_info}
            Question: "{user_question}"
            Answer concisely in 2 to 3 sentences like an authentic F1 engineer on the pit wall.
            """
            resp = client.models.generate_content(
                model="gemini-2.5-flash",
                contents=prompt
            )
            if resp and resp.text:
                return resp.text
        except Exception:
            pass

    q_lower = user_question.lower()
    p1 = pred_df.iloc[0]["driver"]
    p2 = pred_df.iloc[1]["driver"]

    if "undercut" in q_lower or "pit" in q_lower:
        return f"Box opposite to {p2}. If {p2} stays out on lap 20, we box for Hard tires immediately to capitalize on the 1.6-second out-lap delta."
    elif "rain" in q_lower or "weather" in q_lower:
        return "Radar shows rain clouds 8km out with intensity rising. We stay on slicks until sector 2 telemetry confirms lap times dropping by 4 seconds."
    elif "safety car" in q_lower:
        return f"Copy, Delta positive! Pit window is open. If SC is deployed now, we box {p1} for scrubbed Softs to attack on the restart."
    else:
        return f"Understood. We are monitoring sector 2 micro-sectors. Push Mode 6 for two laps to build a 2.5-second buffer over {p2}."
